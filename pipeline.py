
from Ochestrization.gh_job import *
from AgentSide.agent_call import *


def run_pipeline(
    repo: str,
    agent_name: str,
    model_name: str,
    issue_num: int,
) -> str:

    # 1. Repo 준비
    path = prepare_repo(repo)

    # 2. mvp_dev 최신화
    sync_main(path)

    # 3. Issue 조회
    issue = get_issue_content(
        repo,
        issue_num,
    )

    logger.info(
        f"Issue #{issue_num}: {issue['title']}"
    )

    # 4. Agent 작업용 branch 생성
    branch_name = branch_cut(
        path,
        agent_name,
        model_name,
        issue_num,
    )

    # 5. Agent가 코드 수정
    prompt = build_prompt(issue)

    invoke_cline(
        path,
        prompt,
    )

    # 6. Agent 변경사항 commit
    commit_changes(
        path,
        issue_num,
    )

    # 7. Remote branch push
    push_branch(
        path,
        branch_name,
    )

    # 8. PR 생성 -> mvp_dev
    return create_pr(
        path,
        repo,
        branch_name,
        title=f"[{agent_name}/{model_name}] Fix #{issue_num}: {issue['title']}",
        body=(
            f"Closes #{issue_num}\n\n"
            f"Auto-generated by {agent_name} ({model_name})."
        ),
    )

