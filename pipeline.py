def run_pipeline(repo: str, agent_name: str, model_name: str, issue_num: int) -> dict:


    # ================= get repo, issue, branch cut =====================
    path = prepare_repo(repo)
    print(path)
    sync_main(path)

    issue = get_issue_content(repo, issue_num)
    logger.info(f"Issue #{issue_num}: {issue['title']}")

    branch_name = branch_cut(path, agent_name, model_name, issue_num)

    # Phase 1: Cline 연동 전까지는 더미 변경으로 대체
    #temp_code_change(path)
    

    #Phas 2: Cline 연동
    # ================= call cline and write the acutal code =====================

    prompt = build_prompt(issue)
    invoke_cline(path,prompt)


    # ================= Git Add commit get diff  =====================

    SHA = commit_changes(path,f" #{issue_num}: {issue['title']}")
    diff = get_commit_diff(path,SHA)
    # ================= Push branch Create PR   =====================

    push_branch(path, branch_name)

    pr_url= create_pr(
        path, repo,
        title=f"[{agent_name}/{model_name}] Fix #{issue_num}: {issue['title']}",
        body=f"Closes #{issue_num}\n\nAuto-generated by {agent_name} ({model_name}).",
    )
     # ================= Pipeline Result =====================

    return {
        "commit_sha": SHA,
        "diff": diff,
        "pr_url": pr_url,
    }